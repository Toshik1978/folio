package main

import (
	"bytes"
	"go/token"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/suite"
)

func TestLayoutcheck(t *testing.T) {
	suite.Run(t, new(layoutSuite))
}

type layoutSuite struct {
	suite.Suite
}

// messages checks src as the file name and returns its findings as strings.
func (s *layoutSuite) messages(name, src string) []string {
	found, err := checkSource(token.NewFileSet(), name, []byte(src))
	s.Require().NoError(err)
	out := make([]string, 0, len(found))
	for _, f := range found {
		out = append(out, f.String())
	}

	return out
}

func (s *layoutSuite) TestGroupedMethodsPass() {
	s.Empty(s.messages("a.go", `package a

type T struct{}

func NewT() *T { return &T{} }

func (t *T) A() {}
func (t *T) b() {}

type U struct{}

func (U) C() {}

func helper() {}
`))
}

func (s *layoutSuite) TestDeclarationInsideMethodRunIsReported() {
	s.Equal([]string{
		"a.go:6: func helper splits the methods of T; keep a type's methods in one run",
		"a.go:8: type U splits the methods of T; keep a type's methods in one run",
		"a.go:10: method U.C splits the methods of T; keep a type's methods in one run",
		"a.go:12: const block splits the methods of T; keep a type's methods in one run",
	}, s.messages("a.go", `package a

type T struct{}

func (t *T) A() {}
func helper() {}

type U struct{}

func (U) C() {}

const k = 1

func (t T) B() {}
`))
}

func (s *layoutSuite) TestGenericReceiverIsGrouped() {
	s.Len(s.messages("a.go", `package a

type L[T any] struct{}

func (l *L[T]) A() {}
func f() {}
func (l L[T]) B() {}
`), 1)
}

func (s *layoutSuite) TestTestFilesSkipMethodGrouping() {
	s.Empty(s.messages("a_test.go", `package a

type T struct{}

func (t *T) A() {}
func helper() {}
func (t *T) B() {}
`))
}

func (s *layoutSuite) TestInterfaceGuardIsReported() {
	src := `package a

type I interface{ M() }
type T struct{}

func (T) M() {}

var _ I = T{}
var _, ok = 1, true
`
	want := []string{"a.go:8: compile-time interface guard: the consumer's use already checks the type"}
	s.Equal(want, s.messages("a.go", src))
	s.Equal([]string{"a_test.go:8: compile-time interface guard: the consumer's use already checks the type"},
		s.messages("a_test.go", src), "guards are reported in tests too")
}

func (s *layoutSuite) TestGeneratedFileIsSkipped() {
	s.Empty(s.messages("a.go", `// Code generated by sqlc. DO NOT EDIT.

package a

type T struct{}

func (T) A() {}
func f() {}
func (T) B() {}

var _ = f
`))
}

func (s *layoutSuite) TestRunWalksAndSetsExitCode() {
	root := s.T().TempDir()
	write := func(rel, src string) {
		path := filepath.Join(root, rel)
		s.Require().NoError(os.MkdirAll(filepath.Dir(path), 0o750))
		s.Require().NoError(os.WriteFile(path, []byte(src), 0o600))
	}
	write("ok/ok.go", "package ok\n\ntype T struct{}\n\nfunc (T) A() {}\n")
	write("testdata/bad.go", "package bad\n\ntype T struct{}\n\nfunc (T) A() {}\nfunc f() {}\nfunc (T) B() {}\n")

	var out, errOut bytes.Buffer
	s.Equal(0, run([]string{root}, &out, &errOut), "testdata is not walked")
	s.Empty(out.String())

	write("bad/bad.go", "package bad\n\ntype T struct{}\n\nfunc (T) A() {}\nfunc f() {}\nfunc (T) B() {}\n")
	s.Equal(1, run([]string{root}, &out, &errOut))
	s.Contains(out.String(), filepath.Join(root, "bad", "bad.go")+":6: func f splits the methods of T")
	s.Empty(errOut.String())

	write("broken/broken.go", "package broken\n\nfunc {\n")
	s.Equal(2, run([]string{root}, &out, &errOut))
	s.Contains(errOut.String(), "layoutcheck: walk ")
	s.Contains(errOut.String(), "parse ")
}
